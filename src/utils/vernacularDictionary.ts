/**
 * Translates any raw text phrase into the selected language
 */
export function translateText(text: string, lang: SupportedLanguage): string {
  if (!text || lang === 'en') return text;
  const match = VERNACULAR_TRANSLATIONS[text.trim()];
  if (match && match[lang]) {
    return match[lang];
  }
  return text;
}
