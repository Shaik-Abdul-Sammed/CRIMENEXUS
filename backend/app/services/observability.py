# --------------------------------------------------------------------------- #
#  Prometheus Metrics Endpoint Handler                                          #
# --------------------------------------------------------------------------- #
def metrics_endpoint(_request: Request) -> Response:
    """Exposes Prometheus metrics in standard text format."""
    data = generate_latest()
    return Response(content=data, media_type=CONTENT_TYPE_LATEST)


# --------------------------------------------------------------------------- #
#  FastAPI Middleware for automatic request instrumentation                     #
# --------------------------------------------------------------------------- #
class PrometheusMiddleware:
    """Middleware that records per-route HTTP metrics automatically."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        request = Request(scope, receive)
        method = request.method
        path = request.url.path

        # Normalize path patterns to avoid high-cardinality labels
        normalized = path
        for prefix in ["/api/v1/", "/threats/", "/api/"]:
            if path.startswith(prefix):
                parts = path[len(prefix):].split("/")
                normalized = prefix + parts[0]
                break

        start = time.perf_counter()
        status_code = 500

        async def send_wrapper(message):
            nonlocal status_code
            if message["type"] == "http.response.start":
                status_code = message["status"]
            await send(message)

        try:
            await self.app(scope, receive, send_wrapper)
        finally:
            duration = time.perf_counter() - start
            HTTP_REQUEST_COUNT.labels(
                method=method, endpoint=normalized, status_code=str(status_code)
            ).inc()
            HTTP_REQUEST_LATENCY.labels(method=method, endpoint=normalized).observe(duration)


def record_ml_inference(model_name: str, duration_seconds: float):
    """Helper to record ML inference latency from service code."""
    ML_INFERENCE_LATENCY.labels(model_name=model_name).observe(duration_seconds)


def record_alert(alert_type: str, severity: str):
    """Helper to record alert generation metrics."""
    ALERT_GENERATED.labels(alert_type=alert_type, severity=severity).inc()
